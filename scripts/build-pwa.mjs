import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const directory = process.argv[2] ? pathToFileURL(resolve(process.argv[2]) + '/') : new URL('../dist/', import.meta.url);
async function list(path, prefix = '') {
  const entries = await readdir(path, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => (entry.isDirectory() ? list(join(path, entry.name), `${prefix}${entry.name}/`) : [`${prefix}${entry.name}`])),
  );
  return files
    .flat()
    .filter((file) => file !== 'sw.js')
    .sort();
}
const files = await list(directory.pathname);
const hash = createHash('sha256');
for (const file of files) hash.update(file).update(await readFile(new URL(file, directory)));
const version = hash.digest('hex').slice(0, 16);
const worker = `// Generated by scripts/build-pwa.mjs. Cache belongs only to this app scope.
const prefix = 'focusword:' + self.registration.scope + ':';
const cacheName = prefix + '${version}';
const files = ${JSON.stringify(files)};
const urls = files.map((file) => new URL(file, self.registration.scope).href);
const allowed = new Set(urls);
const shell = new URL('index.html', self.registration.scope).href;
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(cacheName).then((cache) => cache.addAll(urls)));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith(prefix) && key !== cacheName).map((key) => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || !request.url.startsWith(self.registration.scope)) return;
  const path = new URL(request.url).pathname;
  const scopePath = new URL(self.registration.scope).pathname;
  if (allowed.has(request.url)) {
    event.respondWith(caches.open(cacheName).then((cache) => cache.match(request, { ignoreVary: true })).then((response) => response || fetch(request)));
  } else if (request.mode === 'navigate' && (path === scopePath || path === scopePath + 'index.html')) {
    // Keep HTML and its hashed assets from the same build; updates activate after tabs close.
    event.respondWith(caches.open(cacheName).then((cache) => cache.match(shell)).then((response) => response || fetch(request)));
  }
});
`;
await writeFile(new URL('sw.js', directory), worker);
console.log(`PWA: ${files.length} static files, cache ${version}`);
